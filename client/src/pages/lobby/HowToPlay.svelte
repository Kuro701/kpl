<h2>Jak hrát?</h2>

Rozdají se Karty
Každý hráč dostane 10 bílých karet

Je zvolen Císař
Jeden z hráčů je zvolen Císařem, který bude v tomto kole rozhodovat o vítězi

Vyber nejvtipnější kartu
Ze svého balíčku vyber kartu, která se nejvíce hodí k vyložené černé kartě

Císař vybere vítěze
Císař přečte nahlas všechny kombinace karet a vybere která je dle jeho názoru nejvtipnější.
